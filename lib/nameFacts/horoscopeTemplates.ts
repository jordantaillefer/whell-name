export function getRandomHoroscope(name: string): string {
  const template =
    HOROSCOPE_TEMPLATES[Math.floor(Math.random() * HOROSCOPE_TEMPLATES.length)];

  return template.replaceAll("{name}", name);
}

export function getDailyHoroscope(name: string, date: Date = new Date()): string {
  const yyyy = date.getFullYear();
  const mm = String(date.getMonth() + 1).padStart(2, "0");
  const dd = String(date.getDate()).padStart(2, "0");
  const seedString = `${name}-${yyyy}-${mm}-${dd}`;

  let hash = 2166136261;
  for (let i = 0; i < seedString.length; i++) {
    hash ^= seedString.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }

  const index = Math.abs(hash) % HOROSCOPE_TEMPLATES.length;
  return HOROSCOPE_TEMPLATES[index].replaceAll("{name}", name);
}
